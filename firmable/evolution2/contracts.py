"""Small model decisions compiled into the existing executable mapping contract."""
from collections import Counter

from pydantic import Field, model_validator

from ..mapping.schema import Strict, FieldRule, Unmapped, RecordId, ObservedAt
from ..evolution.schema import Concept, EntityType, Relation, Role, Edge, Proposal, DynamicMapping, Critique


class Group(Strict):
    name: str = Field(pattern=r"^[a-z][a-z0-9_]*$")
    purpose: str
    columns: list[str] = Field(min_length=1, max_length=24)


class GroupPlan(Strict):
    grain: str
    groups: list[Group] = Field(min_length=1, max_length=12)
    entity_types: list[EntityType] = Field(default_factory=list)
    entities: dict[str, Role] = Field(default_factory=dict)
    relationship_types: list[Relation] = Field(default_factory=list)
    relationships: list[Edge] = Field(default_factory=list)
    cautions: list[str] = Field(default_factory=list)

    def check_columns(self, columns):
        assigned = [c for g in self.groups for c in g.columns]
        if len({g.name for g in self.groups}) != len(self.groups):
            raise ValueError("Group names must be unique")
        duplicate = [c for c, n in Counter(assigned).items() if n > 1]
        if duplicate or set(assigned) != set(columns):
            raise ValueError(f"Assign every source column exactly once. Duplicates={duplicate}; missing={sorted(set(columns)-set(assigned))}; unknown={sorted(set(assigned)-set(columns))}")
        if "subject" in self.entities:
            raise ValueError("subject is implicit; do not redeclare it")
        for role in self.entities.values():
            if set(role.key_paths) - set(columns):
                raise ValueError("Entity key references nonexistent columns")


class ConceptPatch(Strict):
    concepts: list[Concept] = Field(default_factory=list)
    reuse: dict[str, str] = Field(default_factory=dict)


def resolve_patch(revision, previous, registered):
    """A reuse of a prior draft retains that draft, never approves or registers it.

    Omitted concepts are dropped. Only explicitly referenced prior drafts survive;
    replacements remain subject to the normal registry and critic checks.
    """
    drafts = {c.path: c for c in previous.concepts} if previous else {}
    defined = {c.path for c in revision.concepts}
    retained, reuse = [], {}
    for path, reason in revision.reuse.items():
        if path in defined:
            raise ValueError("A revision cannot both define and reuse " + path)
        if path in registered:
            reuse[path] = reason
        elif path in drafts:
            retained.append(drafts[path])
        else:
            raise ValueError("Unknown reuse " + path + "; provide its full definition or select a registered/prior draft concept")
    return ConceptPatch(concepts=revision.concepts + retained, reuse=reuse)


class ClaimPeriod(Strict):
    """Meaning supplied by the model; compiler sets only the named claim's dates."""
    from_column: str | None = None
    to_column: str | None = None
    formats: list[str] | None = None
    meaning: str = Field(min_length=12)

    @model_validator(mode="after")
    def nonempty(self):
        if not self.from_column and not self.to_column:
            raise ValueError("A claim period needs at least one date column")
        return self


class SemanticField(FieldRule):
    """Same conversion allowlist, but claim time has an explicit semantic decision."""
    claim_period: ClaimPeriod | None = None

    @model_validator(mode="after")
    def no_metadata_targets(self):
        if self.target.startswith(("observation.", "confidence.")):
            raise ValueError("Metadata is generated by the executor. For a claim's validity, use claim_period on the affected field. For a separately reported date, propose a date concept with the correct owner.")
        if self.valid_from_path or self.valid_to_path or self.validity_date_formats:
            raise ValueError("Use claim_period with an explanation; executable validity fields are compiler-owned")
        return self


class GroupIntent(Strict):
    fields: list[SemanticField] = Field(default_factory=list)
    unmapped: list[Unmapped] = Field(default_factory=list)


class GroupCritique(Critique):
    repair_scope: str = Field(pattern=r"^(none|mapping|ontology|both)$")


def compile_fields(intent):
    fields = []
    for semantic in intent.fields:
        data = semantic.model_dump(exclude={"claim_period"})
        if semantic.claim_period:
            data.update(valid_from_path=semantic.claim_period.from_column,
                        valid_to_path=semantic.claim_period.to_column,
                        validity_date_formats=semantic.claim_period.formats)
        fields.append(FieldRule.model_validate(data))
    return fields


def compile_mapping(source, inspection, plan, intents, *, outside_columns=(), scoped=False):
    fields = [f for intent in intents for f in compile_fields(intent)]
    if not fields:
        raise ValueError("No executable claims; retain an explicit unsupported group instead")
    consumed = {p for intent in intents for f in intent.fields for p in f.source_paths}
    # A local group's omission is not a veto on another group's accepted value.
    # Keep contradictions within the same intent so static validation rejects them.
    unmapped = [u for intent in intents for u in intent.unmapped
                if u.source_path not in consumed or u.source_path in {p for f in intent.fields for p in f.source_paths}]
    known = {u.source_path for u in unmapped}
    unmapped += [Unmapped(source_path=c, reason="Outside this group; reconciled in the final source mapping") for c in outside_columns if c not in known]
    populated = {f.entity or "subject" for f in fields}
    entities = {k: v for k, v in plan.entities.items() if not scoped or k in populated}
    relationships = [e for e in plan.relationships if not scoped or {e.from_role, e.to_role} <= populated]
    return DynamicMapping(source_id=source["source_id"], record_grain=plan.grain,
        grain_rationale="Model-authored grain and groups; executable envelope compiled deterministically.",
        reader=inspection.reader, record_id=RecordId(strategy="content_hash"), observed_at=ObservedAt(),
        fields=fields, entities=entities, relationships=relationships, unmapped=unmapped,
        notes="Grouped semantic intents; no manually authored mapping rules.")


def whole_patch(plan, patches):
    return Proposal(entity_types=plan.entity_types, relationships=plan.relationship_types,
                    concepts=[c for patch in patches for c in patch.concepts],
                    reuse={k: v for patch in patches for k, v in patch.reuse.items()})
